-- ========================
-- TRIGGERS
-- Automatizam regras do sistema no banco de dados.
-- ========================

-- Trigger responsável por atualizar automaticamente
-- o saldo de pontos do usuário quando houver inserção
-- no histórico de pontos.
CREATE OR REPLACE TRIGGER trg_historico_pontos_usuario
AFTER INSERT ON HISTORICO_PONTOS
FOR EACH ROW
BEGIN
    -- Se a movimentação for entrada, soma pontos ao usuário
    IF :NEW.tipo_movimentacao = 'ENTRADA' THEN
        UPDATE USUARIO
        SET saldo_pontos = saldo_pontos + :NEW.pontos
        WHERE id_usuario = :NEW.id_usuario;

    -- Se a movimentação for saída, subtrai pontos do usuário
    ELSIF :NEW.tipo_movimentacao = 'SAIDA' THEN
        UPDATE USUARIO
        SET saldo_pontos = saldo_pontos - :NEW.pontos
        WHERE id_usuario = :NEW.id_usuario;
    END IF;
END;
/

-- Trigger responsável por reduzir automaticamente
-- o estoque da recompensa após um resgate.
CREATE OR REPLACE TRIGGER trg_baixa_estoque_recompensa
AFTER INSERT ON RESGATE_RECOMPENSA
FOR EACH ROW
BEGIN
    UPDATE RECOMPENSA
    SET quantidade_estoque = quantidade_estoque - 1
    WHERE id_recompensa = :NEW.id_recompensa
    AND quantidade_estoque > 0;
END;
