CREATE INDEX idx_item_descarte ON ITEM_DESCARTE(id_descarte);

-- Índice para buscas por tipo de material em ITEM_DESCARTE
CREATE INDEX idx_item_material ON ITEM_DESCARTE(id_tipo_material);

-- Índice para buscas por usuário em RESGATE_RECOMPENSA
CREATE INDEX idx_resgate_usuario ON RESGATE_RECOMPENSA(id_usuario);

-- Índice para buscas por recompensa em RESGATE_RECOMPENSA
CREATE INDEX idx_resgate_recompensa ON RESGATE_RECOMPENSA(id_recompensa);

-- Índice para buscas por usuário em HISTORICO_PONTOS
CREATE INDEX idx_historico_usuario ON HISTORICO_PONTOS(id_usuario);

